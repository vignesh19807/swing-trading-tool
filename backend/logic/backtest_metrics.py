"""
Week 12 - Backtest Metrics Calculator
======================================

Calculates deterministic performance metrics for historical backtests, ensuring robust
handling of edge cases (zero trades, zero winning trades, all open trades, etc.)
without division-by-zero crashes or misleading outputs.

Author: Logic Engineer
"""

import math
from typing import Any, Dict, List
from backend.logic.backtest_specification import TradeState


def _is_valid_num(val: Any) -> bool:
    """Check if value is a valid finite integer or float."""
    if val is None or isinstance(val, bool) or not isinstance(val, (int, float)):
        return False
    if isinstance(val, float) and (math.isnan(val) or math.isinf(val)):
        return False
    return True


def calculate_backtest_metrics(
    trades: List[Dict[str, Any]],
    strict_mode: bool = False,
    portfolio_equity_curve: Optional[List[Dict[str, Any]]] = None,
    initial_capital: Optional[float] = None
) -> Dict[str, Any]:
    """
    Computes deterministic performance metrics for a list of simulated trade records.

    Parameters
    ----------
    trades : list of dict
        List of trade records generated by trade_simulator or portfolio_simulator.
    strict_mode : bool, default False
        When True, strictly handles unavailable metrics: returns None (rather than
        0.0 or arbitrary numbers) when metrics are mathematically undefined
        (e.g., zero closed trades, zero losses for profit factor).
    portfolio_equity_curve : list of dict, optional
        Precomputed chronological portfolio equity series from portfolio simulation.
    initial_capital : float, optional
        Initial cash balance to compute exact portfolio return percentage.

    Returns
    -------
    dict
        Structured summary of performance metrics.
    """
    if not trades or not isinstance(trades, list):
        curve = portfolio_equity_curve or []
        mdd = None if strict_mode else 0.0
        if curve and any("drawdown_pct" in pt for pt in curve):
            mdd = max(pt.get("drawdown_pct", 0.0) for pt in curve)
        return {
            "total_trades": 0,
            "closed_trades": 0,
            "open_trades": 0,
            "invalid_trades": 0,
            "incomplete_trades": 0,
            "winning_trades": 0,
            "losing_trades": 0,
            "breakeven_trades": 0,
            "win_rate": None if strict_mode else 0.0,
            "total_pl": None if strict_mode else 0.0,
            "gross_pl": None if strict_mode else 0.0,
            "total_costs": None if strict_mode else 0.0,
            "net_pl": None if strict_mode else 0.0,
            "total_return_pct": None if strict_mode else 0.0,
            "avg_trade_return_pct": None if strict_mode else 0.0,
            "avg_winning_trade_pct": None if strict_mode else 0.0,
            "avg_losing_trade_pct": None if strict_mode else 0.0,
            "profit_factor": None if strict_mode else 0.0,
            "max_drawdown_pct": mdd,
            "equity_curve": curve,
        }

    total_trades = len(trades)
    closed_trades_list = [t for t in trades if isinstance(t, dict) and t.get("status") in (TradeState.CLOSED, "CLOSED")]
    open_trades_list = [t for t in trades if isinstance(t, dict) and t.get("status") in (TradeState.OPEN, "OPEN")]
    invalid_trades_list = [t for t in trades if isinstance(t, dict) and t.get("status") in (TradeState.INVALID, "INVALID")]
    incomplete_trades_list = [t for t in trades if isinstance(t, dict) and t.get("status") in (TradeState.INCOMPLETE, "INCOMPLETE")]

    closed_count = len(closed_trades_list)
    open_count = len(open_trades_list)
    invalid_count = len(invalid_trades_list)
    incomplete_count = len(incomplete_trades_list)

    # Winning vs Losing vs Breakeven trades (among CLOSED trades)
    winning_trades = [t for t in closed_trades_list if _is_valid_num(t.get("pl")) and t.get("pl") > 0]
    breakeven_trades = [t for t in closed_trades_list if _is_valid_num(t.get("pl")) and t.get("pl") == 0]
    if strict_mode:
        losing_trades = [t for t in closed_trades_list if _is_valid_num(t.get("pl")) and t.get("pl") < 0]
    else:
        # Legacy compat: lump non-positive trades together if not strict
        losing_trades = [t for t in closed_trades_list if _is_valid_num(t.get("pl")) and t.get("pl") <= 0]

    win_count = len(winning_trades)
    loss_count = len(losing_trades)
    breakeven_count = len(breakeven_trades)

    # Win Rate calculation: winning closed trades / total eligible closed trades
    if closed_count > 0:
        win_rate = round((win_count / closed_count) * 100.0, 4)
    else:
        win_rate = None if strict_mode else 0.0

    # P/L & Return calculations
    all_pls = [t.get("pl") for t in closed_trades_list if _is_valid_num(t.get("pl"))]
    total_pl = round(sum(all_pls), 4) if all_pls else (None if strict_mode else 0.0)

    # Itemized gross P/L, total costs, and net P/L
    gross_pls = [t.get("gross_pl") for t in closed_trades_list if _is_valid_num(t.get("gross_pl"))]
    gross_pl = round(sum(gross_pls), 4) if gross_pls else (total_pl if total_pl is not None else (None if strict_mode else 0.0))

    all_costs = [t.get("total_costs") for t in closed_trades_list if _is_valid_num(t.get("total_costs"))]
    total_costs = round(sum(all_costs), 4) if all_costs else (0.0 if not strict_mode else (0.0 if closed_count > 0 else None))

    net_pls = [t.get("net_pl") for t in closed_trades_list if _is_valid_num(t.get("net_pl"))]
    net_pl = round(sum(net_pls), 4) if net_pls else total_pl

    all_returns = [t.get("return_pct") for t in closed_trades_list if _is_valid_num(t.get("return_pct"))]
    total_return_pct = round(sum(all_returns), 4) if all_returns else (None if strict_mode else 0.0)

    # If portfolio_equity_curve and initial_capital are provided, use exact portfolio return %
    if portfolio_equity_curve and initial_capital and initial_capital > 0:
        final_eq = portfolio_equity_curve[-1].get("equity")
        if _is_valid_num(final_eq):
            total_return_pct = round(((final_eq - initial_capital) / initial_capital) * 100.0, 4)

    avg_trade_return_pct = round(total_return_pct / closed_count, 4) if (closed_count > 0 and total_return_pct is not None) else (None if strict_mode else 0.0)

    win_returns = [t.get("return_pct") for t in winning_trades if _is_valid_num(t.get("return_pct"))]
    avg_winning_trade_pct = round(sum(win_returns) / win_count, 4) if win_count > 0 else (None if strict_mode else 0.0)

    loss_returns = [t.get("return_pct") for t in losing_trades if _is_valid_num(t.get("return_pct"))]
    avg_losing_trade_pct = round(sum(loss_returns) / loss_count, 4) if loss_count > 0 else (None if strict_mode else 0.0)

    # Profit Factor calculation: gross realized profits / absolute gross realized losses
    # Uses gross_pl if available, else pl
    def _trade_profit(t):
        val = t.get("gross_pl")
        return val if _is_valid_num(val) else t.get("pl")

    gross_profits = sum([_trade_profit(t) for t in winning_trades if _is_valid_num(_trade_profit(t))])
    gross_losses = abs(sum([_trade_profit(t) for t in losing_trades if _is_valid_num(_trade_profit(t))]))

    if gross_losses > 0:
        profit_factor = round(gross_profits / gross_losses, 4)
    elif gross_profits > 0:
        # Zero losses: mathematically undefined (division by zero)
        # In strict_mode, return None rather than fabricating an arbitrary finite ratio
        profit_factor = None if strict_mode else round(gross_profits, 4)
    else:
        profit_factor = None if strict_mode else 0.0

    # Maximum Drawdown and Equity Curve calculation
    if portfolio_equity_curve:
        equity_curve = portfolio_equity_curve
        dds = [pt.get("drawdown_pct") for pt in portfolio_equity_curve if _is_valid_num(pt.get("drawdown_pct"))]
        max_drawdown_pct = round(max(dds), 4) if dds else (None if strict_mode else 0.0)
    else:
        max_drawdown_pct = None if strict_mode else 0.0
        equity_curve = []

        def _get_trade_date(t):
            return t.get("exit_date") or t.get("entry_date") or t.get("evaluation_date") or ""

        dated_closed_trades = [t for t in closed_trades_list if _is_valid_num(t.get("return_pct")) or _is_valid_num(t.get("pl"))]
        dated_closed_trades.sort(key=_get_trade_date)

        if dated_closed_trades:
            cum = 0.0
            peak = 0.0
            max_dd = 0.0
            for t in dated_closed_trades:
                ret = t.get("return_pct")
                if not _is_valid_num(ret) and _is_valid_num(t.get("pl")) and _is_valid_num(t.get("entry_price")) and t["entry_price"] > 0:
                    ret = (t["pl"] / t["entry_price"]) * 100.0
                r_val = float(ret) if _is_valid_num(ret) else 0.0
                cum += r_val
                if cum > peak:
                    peak = cum
                dd = peak - cum
                if dd > max_dd:
                    max_dd = dd

                date_str = _get_trade_date(t)
                equity_curve.append({
                    "date": date_str,
                    "equity": round(100.0 + cum, 2),
                    "drawdown_pct": round(dd, 4)
                })

            max_drawdown_pct = round(max_dd, 4)
        elif not strict_mode and all_returns:
            # Fallback for non-dated legacy lists
            cum_returns = []
            cum = 0.0
            for r in all_returns:
                cum += r
                cum_returns.append(cum)

            peak = cum_returns[0]
            max_dd = 0.0
            for val in cum_returns:
                if val > peak:
                    peak = val
                dd = peak - val
                if dd > max_dd:
                    max_dd = dd
            max_drawdown_pct = round(max_dd, 4)

    return {
        "total_trades": total_trades,
        "closed_trades": closed_count,
        "open_trades": open_count,
        "invalid_trades": invalid_count,
        "incomplete_trades": incomplete_count,
        "winning_trades": win_count,
        "losing_trades": loss_count,
        "breakeven_trades": breakeven_count,
        "win_rate": win_rate,
        "total_pl": total_pl,
        "gross_pl": gross_pl,
        "total_costs": total_costs,
        "net_pl": net_pl,
        "total_return_pct": total_return_pct,
        "avg_trade_return_pct": avg_trade_return_pct,
        "avg_winning_trade_pct": avg_winning_trade_pct,
        "avg_losing_trade_pct": avg_losing_trade_pct,
        "profit_factor": profit_factor,
        "max_drawdown_pct": max_drawdown_pct,
        "equity_curve": equity_curve,
    }
